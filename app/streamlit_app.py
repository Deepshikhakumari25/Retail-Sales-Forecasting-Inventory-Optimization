"""Beginner-friendly interactive retail forecasting and inventory dashboard."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import matplotlib.pyplot as plt
import pandas as pd
import streamlit as st

from retail_forecasting.data_loader import load_retail_data
from retail_forecasting.data_validation import data_quality_summary
from retail_forecasting.evaluation import evaluate_models
from retail_forecasting.forecasting import forecast_series
from retail_forecasting.inventory import replenishment_recommendation
from retail_forecasting.reporting import export_purchase_order
from main import _recommendations

st.set_page_config(page_title="Retail Forecasting & Inventory Planner", page_icon="📦", layout="wide")
st.title("AI-Powered Retail Sales Forecasting & Inventory Optimization")
st.caption("Educational planning simulation. Synthetic data and cost assumptions are clearly labeled.")


@st.cache_data
def load_data() -> pd.DataFrame:
    sample = ROOT / "data" / "sample" / "retail_sales.csv"
    user_file = ROOT / "data" / "raw" / "retail_sales.csv"
    selected = user_file if user_file.exists() else sample
    return load_retail_data(selected if selected.exists() else None, fallback=True)


@st.cache_data
def evaluate_data(data: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame, str]:
    scores, metadata = evaluate_models(data)
    return scores, metadata["comparison"], str(metadata["selected_model"])


try:
    data = load_data()
except (ValueError, OSError) as error:
    st.error(f"Could not load retail data: {error}")
    st.stop()

with st.sidebar:
    st.header("Controls")
    page = st.radio("Navigate", ["Overview", "Demand Analysis", "Forecasting", "Inventory Optimization", "Purchase Order Export", "Data and Assumptions"])
    stores = sorted(data["store_id"].unique())
    selected_store = st.selectbox("Store", stores)
    items = sorted(data.loc[data["store_id"] == selected_store, "item_id"].unique())
    selected_item = st.selectbox("Product", items)
    horizon = st.slider("Forecast horizon (days)", min_value=7, max_value=56, value=28, step=7)

selected = data.loc[(data["store_id"] == selected_store) & (data["item_id"] == selected_item)].sort_values("date")
recommendations = _recommendations(data)
recommendations["data_source"] = recommendations.get("data_source", "synthetic_simulation")

if page == "Overview":
    try:
        scores, _, selected_model = evaluate_data(data)
        selected_score = scores.loc[scores["model"] == selected_model].iloc[0]
    except ValueError as error:
        selected_model, selected_score = "Unavailable", None
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Units sold", f"{int(data['qty_sold'].sum()):,}")
    c2.metric("Stores", int(data["store_id"].nunique()))
    c3.metric("Products", int(data["item_id"].nunique()))
    c4.metric("Replenishment alerts", int((recommendations["recommended_order_qty"] > 0).sum()))
    if selected_score is not None:
        st.metric("Selected holdout model", selected_model)
        st.caption(f"Chronological holdout MAE: {selected_score['mae']:.2f} units")
    else:
        st.warning(f"Model metrics are unavailable for this dataset: {error}")
    st.subheader("Recent demand")
    daily = data.groupby("date", as_index=False)["qty_sold"].sum().tail(180)
    st.line_chart(daily.set_index("date"))
    st.caption(f"Forecast horizon control: {horizon} days. Full model metrics are generated by `python main.py`.")
    st.dataframe(recommendations[recommendations["recommended_order_qty"] > 0].head(10), use_container_width=True)

elif page == "Demand Analysis":
    st.subheader("Historical demand and weekly pattern")
    left, right = st.columns(2)
    with left:
        st.line_chart(data.groupby("date")["qty_sold"].sum())
        if "category" in data:
            st.bar_chart(data.groupby("category")["qty_sold"].sum().sort_values(ascending=False))
    with right:
        weekday = data.assign(weekday=pd.to_datetime(data["date"]).dt.day_name()).groupby("weekday")["qty_sold"].mean()
        st.bar_chart(weekday.reindex(["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]))
        product_stats = data.groupby("item_id")["qty_sold"].agg(mean="mean", zero_share=lambda values: (values == 0).mean()).sort_values("mean")
        st.dataframe(product_stats, use_container_width=True)
    if "promo_flag" in data:
        st.write("Mean observed units by promotion flag")
        st.bar_chart(data.groupby("promo_flag")["qty_sold"].mean())
    st.caption("Observed zero sales may represent genuine zeros or stockout-censored demand; lost sales are not imputed.")

elif page == "Forecasting":
    st.subheader(f"{selected_store} / {selected_item}: forecast")
    model_choice = st.selectbox("Forecast model", ["seasonal_naive", "random_forest", "croston_sba"])
    try:
        predictions, model_name = forecast_series(selected, horizon, model_choice)
        dates = pd.date_range(selected["date"].max() + pd.Timedelta(days=1), periods=horizon)
        future = pd.DataFrame({"date": dates, "Expected units": predictions}).set_index("date")
        history = selected.set_index("date")["qty_sold"].tail(90).rename("Historical units")
        chart = pd.concat([history, future], axis=1)
        st.line_chart(chart)
        st.info(f"Model: {model_name}. Expected demand remains fractional; purchase quantities are rounded up.")
    except (ValueError, KeyError) as error:
        st.warning(f"A forecast could not be produced for this selection: {error}")
    try:
        scores, comparison, _ = evaluate_data(data)
        st.subheader("Chronological holdout model comparison")
        st.dataframe(scores, use_container_width=True)
        st.caption("Validation MAE selected the model; final test MAE/RMSE are rolling one-step metrics. MASE may be undefined for flat training series.")
    except ValueError as error:
        st.warning(f"Model comparison is unavailable for this dataset: {error}")
    else:
        chosen = comparison.loc[
            (comparison["store_id"] == selected_store) & (comparison["item_id"] == selected_item)
        ].set_index("date")
        if not chosen.empty:
            st.subheader("Actual versus held-out one-step predictions")
            st.line_chart(chosen[["qty_sold", "seasonal_naive", "random_forest"]].rename(columns={
                "qty_sold": "Actual", "seasonal_naive": "Seasonal Naive", "random_forest": "Random Forest"
            }))

elif page == "Inventory Optimization":
    st.subheader("Replenishment recommendations")
    st.caption("Safety stock uses z × daily demand standard deviation × √lead time. Order quantity follows a lead-time-plus-28-day order-up-to policy. EOQ is informational.")
    st.dataframe(recommendations, use_container_width=True)
    current = recommendations.loc[(recommendations["store_id"] == selected_store) & (recommendations["item_id"] == selected_item)].iloc[0]
    st.metric("Recommended units", int(current["recommended_order_qty"]), str(current["status"]))
    st.write(current["explanation"])
    order_value = current["estimated_order_value"]
    st.metric(
        "Estimated order value (simulated cost units)",
        f"{order_value:,.2f}" if pd.notna(order_value) else "Not available",
    )

elif page == "Purchase Order Export":
    st.subheader("Open simulated purchase order lines")
    orders = recommendations.loc[recommendations["recommended_order_qty"] > 0]
    st.dataframe(orders, use_container_width=True)
    csv = orders.to_csv(index=False).encode("utf-8")
    st.download_button("Download purchase order CSV", csv, "purchase_order.csv", "text/csv")
    st.caption("Costs are synthetic assumptions, not quotes or real procurement instructions.")

else:
    st.subheader("Data source and quality")
    source = str(data["data_source"].iloc[0]) if "data_source" in data else "user-provided CSV"
    st.write(f"Active data label: **{source}**")
    st.json(data_quality_summary(data))
    st.markdown(
        """
        - Place an optional CSV at `data/raw/retail_sales.csv`; otherwise the reproducible offline sample is used.
        - Core columns: `date`, `store_id`, `item_id`, `qty_sold`. Optional fields include price, promotions,
          inventory, lead time and simulated costs.
        - Forecasts are educational estimates, not production recommendations. Stockout observations are
          observed sales and can understate latent demand.
        - Safety stock assumes independent daily variation and a fixed lead time. EOQ assumes stable demand
          and costs. Service-level z values use a normal approximation.
        """
    )
